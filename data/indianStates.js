// Match a state name from Google Maps ("Delhi", "Jammu & Kashmir"…) to one in the list.
const norm = (s) => String(s || "").toLowerCase().replace(/&/g, "and").replace(/[^a-z]/g, "");
export const matchIndianState = (name) => (name ? INDIAN_STATES.find((s) => norm(s) === norm(name)) || "" : "");
